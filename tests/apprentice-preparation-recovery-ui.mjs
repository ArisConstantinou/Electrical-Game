import assert from 'node:assert/strict';
import { mkdir, writeFile } from 'node:fs/promises';
import { pathToFileURL } from 'node:url';
import path from 'node:path';
import os from 'node:os';
import { chromium } from 'playwright';
import { routeBuildingDist } from './building-qa-utils.mjs';
import { blockPointerLock } from './browser-safety.mjs';
const { launchManagedBrowser, runManagedClient } = await import(pathToFileURL(path.join(process.env.CODEX_HOME ?? path.join(os.homedir(), '.codex'), 'skills/develop-web-game/scripts/browser_lifecycle.mjs')));
const before = process.argv.includes('--before');
const out = `output/loading-35-recovery/apprentices-${before ? 'before' : 'after'}`;
await mkdir(out, { recursive: true });
const report = { delivery: 'Compiled candidate on the unchanged 5365 origin', cases: [], errors: [] };
const session = await launchManagedBrowser(chromium, { channel: 'chrome', headless: true, screenshotDir: out });
await runManagedClient(session, 180000, async () => {
  const context = await session.browser.newContext({ viewport: { width: 430, height: 932 }, deviceScaleFactor: 3, isMobile: true, hasTouch: true });
  await routeBuildingDist(context, path.resolve(before ? 'output/loading-35-recovery/baseline-dist' : 'dist')); await blockPointerLock(context);
  const page = await context.newPage(); page.on('pageerror', error => report.errors.push(error.message));
  await page.goto('http://127.0.0.1:5365/Electrical-Game/?renderer=webgl', { waitUntil: 'domcontentloaded' });
  await page.locator('[data-apprentice-count="5"]').tap();
  await page.waitForFunction(() => window.__wireTheHouse?.isReadyForStart, null, { timeout: 90000 });
  const state = await page.evaluate(() => {
    const g = window.__wireTheHouse, b = document.querySelector('#start-button');
    return { text: b.textContent, disabled: b.disabled, labelPresent: !!document.querySelector('#start-button-label'),
      progressPresent: !!document.querySelector('#start-load-percent'), label: document.querySelector('#start-button-label')?.textContent,
      count: g.apprentice.count, loadedCrew: g.apprentice.crew.map(worker => worker.body.loaded), ready: g.isReadyForStart };
  });
  report.cases.push({ name: 'select-five-during-startup', state });
  await page.screenshot({ path: `${out}/five-selected-during-loading.png` });
  await writeFile(`${out}/report.json`, JSON.stringify(report, null, 2));
  console.log(JSON.stringify(state));
  assert(state.labelPresent && state.progressPresent, 'Selecting apprentices must preserve loading and Retry elements');
  assert.equal(state.label, 'READY'); assert.equal(state.disabled, false); assert.equal(state.count, 5);
  assert(state.loadedCrew.length === 4 && state.loadedCrew.every(Boolean));
  for (const count of [0, 1, 5]) {
    await page.locator(`[data-apprentice-count="${count}"]`).tap();
    await page.waitForFunction(count => window.__wireTheHouse.apprentice.count === count && !document.querySelector('#start-button').disabled, count);
    assert.equal(await page.locator('#start-button-label').textContent(), 'READY');
    assert.equal(await page.locator('#start-load-percent').count(), 1);
  }
  await page.locator('#start-button').tap();
  assert.equal(await page.evaluate(() => window.__wireTheHouse.started), true);
  report.cases.push({ name: 'zero-one-five-after-ready-and-start', passed: true });
  await page.goto('http://127.0.0.1:5365/Electrical-Game/?renderer=webgl', { waitUntil: 'domcontentloaded' });
  await page.waitForFunction(() => window.__wireTheHouse?.isReadyForStart, null, { timeout: 90000 });
  await page.locator('[data-apprentice-count="5"]').tap();
  await page.waitForFunction(() => !document.querySelector('#start-button').disabled);
  assert.equal(await page.locator('#start-button-label').textContent(), 'READY');
  assert.equal(await page.evaluate(() => window.__wireTheHouse.apprentice.crew.every(worker => worker.body.loaded)), true);
  report.cases.push({ name: 'create-five-after-ready', passed: true });
  let attempts = 0;
  await context.route('**/assets/vegetation/courtyard-tree/courtyard-tree-optimized.glb*', route => ++attempts <= 3 ? route.abort('failed') : route.fallback());
  await page.goto('http://127.0.0.1:5365/Electrical-Game/?renderer=webgl', { waitUntil: 'domcontentloaded' });
  await page.locator('[data-apprentice-count="1"]').tap();
  await page.waitForFunction(() => document.querySelector('#start-button-label')?.textContent === 'RETRY LOADING', null, { timeout: 45000 });
  assert.equal(await page.locator('#start-load-percent').textContent(), 'LOAD FAILED');
  assert.equal(await page.locator('#start-button').isEnabled(), true);
  // Creating additional crew after failure must leave the native Retry usable.
  await page.locator('[data-apprentice-count="5"]').tap();
  assert.equal(await page.locator('#start-button-label').textContent(), 'RETRY LOADING');
  assert.equal(await page.locator('#start-button').isEnabled(), true);
  await page.screenshot({ path: `${out}/five-selected-failure.png` });
  await Promise.all([page.waitForEvent('domcontentloaded'), page.locator('#start-button').tap()]);
  await page.waitForFunction(() => window.__wireTheHouse?.isReadyForStart, null, { timeout: 90000 });
  assert.equal(await page.locator('#start-button-label').textContent(), 'READY');
  report.cases.push({ name: 'crew-selection-preserves-failure-and-native-retry', attempts, passed: true });
  let modelAttempts = 0;
  await context.route('**/assets/worker/worker-apprentice-lod.glb*', route => ++modelAttempts <= 3 ? route.abort('failed') : route.fallback());
  await page.goto('http://127.0.0.1:5365/Electrical-Game/?renderer=webgl', { waitUntil: 'domcontentloaded' });
  await page.locator('[data-apprentice-count="5"]').tap();
  await page.waitForFunction(() => document.querySelector('#start-button-label')?.textContent === 'RETRY LOADING', null, { timeout: 45000 });
  assert.equal(modelAttempts, 3);
  assert.equal(await page.locator('#start-load-percent').textContent(), 'LOAD FAILED');
  assert((await page.locator('#start-load-error').textContent()).includes('Apprentice model'));
  await Promise.all([page.waitForEvent('domcontentloaded'), page.locator('#start-button').tap()]);
  await page.waitForFunction(() => window.__wireTheHouse?.isReadyForStart, null, { timeout: 90000 });
  assert.equal(modelAttempts, 4);
  report.cases.push({ name: 'selected-crew-model-failure-and-reload', attempts: modelAttempts, passed: true });
  let pendingModelAttempts = 0;
  await context.route('**/assets/worker/worker-apprentice-lod.glb*', route => ++pendingModelAttempts === 1 ? undefined : route.fallback());
  await page.goto('http://127.0.0.1:5365/Electrical-Game/?renderer=webgl', { waitUntil: 'domcontentloaded' });
  await page.locator('[data-apprentice-count="5"]').tap();
  await page.waitForFunction(() => window.__wireTheHouse?.isReadyForStart, null, { timeout: 90000 });
  assert.equal(pendingModelAttempts, 2, 'A pending apprentice request must be cancelled and retried');
  assert.equal(await page.locator('#start-button-label').textContent(), 'READY');
  report.cases.push({ name: 'pending-crew-model-deadline-recovers', attempts: pendingModelAttempts, passed: true });
  assert.deepEqual(report.errors, []);
  await writeFile(`${out}/report.json`, JSON.stringify(report, null, 2));
  console.log(JSON.stringify({ passed: report.cases.length, pageErrors: report.errors }));
  await context.close();
});
